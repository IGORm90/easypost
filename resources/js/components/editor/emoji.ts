/**
 * The emoji the picker offers, grouped the way the picker draws them.
 *
 * Deliberately a hand-kept dataset rather than an npm emoji library:
 * the popular ones ship hundreds of kilobytes of full Unicode data plus
 * their own stylesheets, and those stylesheets carry hex literals, which
 * `resources/js/__tests__/palette.spec.ts` fails the build over. A few
 * hundred entries cover what people actually reach for in a social post,
 * and this file stays inspectable.
 *
 * `en`/`ru` are search keywords, not UI strings — they are what the
 * search box matches against, and a Russian-speaking user must be able
 * to find a smile by typing "улыбка". They are therefore NOT part of the
 * i18n bundles and not subject to the locale-parity guard (which governs
 * `lang/**` and `i18n/*.json`). The category *labels* are UI strings and
 * do live in those bundles, keyed `editor.emoji.categories.*`.
 */
export interface Emoji {
    /** The character itself — what gets inserted. */
    char: string;
    /** English search keywords, space separated. */
    en: string;
    /** Russian search keywords, space separated. */
    ru: string;
}

export interface EmojiCategory {
    /** Key into `editor.emoji.categories.*` for the visible label. */
    key: string;
    emoji: Emoji[];
}

