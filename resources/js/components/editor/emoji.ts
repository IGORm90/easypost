/**
 * Emoji whose keywords (in either language) all match the query. Words
 * are ANDed rather than ORed so that a second word narrows instead of
 * widening — typing "green heart" should not surface every heart.
 */
export function searchEmoji(query: string): Emoji[] {
    const terms = query.trim().toLowerCase().split(/\s+/).filter(Boolean);

    if (terms.length === 0) {
        return [];
    }

    return EMOJI_CATEGORIES.flatMap((category) => category.emoji).filter((emoji) => {
        const haystack = `${emoji.en} ${emoji.ru}`.toLowerCase();

        return terms.every((term) => haystack.includes(term) || emoji.char === term);
    });
}
